sp1 = d.task(57, 52, "Verificar teléfono\npor WhatsApp", None, w=14, h=8, sub=True)
g2 = d.gateway(70, 52, "x", None)
d.ax.text(72.6, 54.6, "¿Confirmada?", fontsize=FS - 0.6, ha="left", va="bottom")
e1 = d.event(70, 59.2, "end", None, "Reserva expirada", r=1.5, label_pos="left")
t2 = d.task(40, 28, "Validar link y\ncontraseña", "service", w=14, h=8)
g3 = d.gateway(53, 28, "x", "¿Válida?", label_pos="above")
e2 = d.event(53, 22.4, "end", None, "Acceso rechazado", r=1.5, label_pos="right")
t3 = d.task(64, 28, "Registrar reserva\nde convenio", "service", w=13, h=8)
g4 = d.gateway(80, 40, "x", None)
t5 = d.task(92, 40, "Registrar estado\nSOLICITADO y\nnotificar", "send", w=13, h=9)
e3 = d.event(102, 40, "end", None, "Reserva\nSOLICITADO", r=1.5)

s2 = d.event(14, 12, "start", "message", "Llamada o\nWhatsApp", label_pos="below")
t4 = d.task(31, 12, "Ingresar reserva\nen el panel", "user", w=14, h=8)

# flujos de secuencia
d.flow([R(s1), L(g1)])
d.flow([T(g1), (27, 52), L(t1)], "Formulario\npúblico", lpos=(26.4, 47.5), lalign="right")
