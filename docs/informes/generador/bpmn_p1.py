d.flow([R(t1), L(sp1)])
d.flow([R(sp1), L(g2)])
d.flow([T(g2), (70, 57.7)], "No", lpos=(70.6, 55.5))
d.flow([R(g2), (80, 52), T(g4)], "Sí", lpos=(73, 52.4))
d.flow([R(t2), L(g3)])
d.flow([B(g3), (53, 23.9)], "No", lpos=(53.6, 24.4))
d.flow([R(g3), L(t3)], "Sí", lpos=(55.6, 28.4))
d.flow([R(t3), (75, 28), (75, 40), L(g4)])
d.flow([R(s2), L(t4)])
d.flow([R(t4), (80, 12), B(g4)])
d.flow([R(g4), L(t5)])
d.flow([R(t5), L(e3)])

# flujos de mensaje
d.msg([(19, 68), (19, 41.6)], "datos del viaje", lpos=(19.6, 64))
