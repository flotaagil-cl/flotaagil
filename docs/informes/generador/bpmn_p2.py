# ---------------- P2: Despacho y asignación de viajes (TO-BE) ----------------
d = BPMN(125, 90)
d.pool(4, 80, 117, 7, "Pasajero", blackbox=True)
d.pool(4, 4, 117, 70, "Empresa de taxi turismo (FlotaÁgil)")
d.lane(7, 38, 114, 36, "Plataforma FlotaÁgil", 0)
d.lane(7, 22, 114, 16, "Despachador", 1)
d.lane(7, 4, 114, 18, "Conductor (app)", 0)

s = d.event(13, 52, "start", None, "Reserva en\nSOLICITADO")
ti = d.event(20, 52, "inter", "timer", "Ventana de\ndespacho", r=1.5)
gm = d.gateway(28, 52, "x")
g1 = d.gateway(36, 52, "x")
d.ax.text(34.6, 49.4, "¿Recogida en\naeropuerto?", fontsize=FS - 0.6, ha="right", va="top")
ta = d.task(50, 64, "Proponer primer\nconductor de la\nfila virtual (P2.1)", "service", w=15, h=8)
tb = d.task(50, 52, "Calcular sugerencias\npor distancia y turno", "service", w=15, h=7)
gj = d.gateway(63, 52, "x")
tc = d.task(63, 30, "Confirmar conductor\nsugerido u otro", "user", w=15, h=7)
td = d.task(78, 52, "Enviar asignación\n(ASIGNADO)", "send", w=14, h=7)
te = d.task(88, 13, "Aceptar o rechazar\nel viaje", "user", w=14, h=7)
bt = d.boundary_timer(te, None, frac=0.5)
d.ax.text(86.4, 8.4, "60 s sin\nrespuesta", fontsize=FS - 1, ha="right", va="top")
gr = d.gateway(101, 13, "x")
d.ax.text(101, 16.0, "¿Acepta?", fontsize=FS - 0.6, ha="center", va="bottom")
gx = d.gateway(113, 13, "x")
tf = d.task(101, 52, "Notificar conductor\nasignado", "send", w=14, h=7)
ef = d.event(105, 60.5, "end", None, None, r=1.5)
d.ax.text(103.2, 60.5, "Viaje\nACEPTADO", fontsize=FS - 0.6, ha="right", va="center")
tg = d.task(113, 64, "Devolver reserva\na SOLICITADO", "service", w=14, h=7)

d.flow([R(s), L(ti)])
d.flow([R(ti), L(gm)])
d.flow([R(gm), L(g1)])
d.flow([T(g1), (36, 64), L(ta)], "Sí", lpos=(36.6, 60.5))
d.flow([R(g1), L(tb)], "No", lpos=(38.6, 52.4))
d.flow([R(ta), (63, 64), T(gj)])
d.flow([R(tb), L(gj)])
d.flow([B(gj), T(tc)])
d.flow([R(tc), (78, 30), B(td)])
d.flow([R(td), (88, 52), T(te)])
d.flow([R(te), L(gr)])
d.flow([T(gr), B(tf)], "Sí", lpos=(101.6, 18.5))
d.flow([(105, 55.5), (105, 59.0)])
d.flow([R(gr), L(gx)], "No", lpos=(104, 13.4))
d.flow([(88, 8.2), (88, 6.0), (113, 6.0), B(gx)])
d.flow([T(gx), B(tg)])
d.flow([T(tg), (113, 71), (28, 71), T(gm)])
d.msg([(97, 55.5), (97, 80)], "datos del conductor\ny del vehículo", lpos=(96.4, 76.5), lalign="right")
d.save("fig/bpmn_p2.png")

